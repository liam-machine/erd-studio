#!/usr/bin/env node
// Writes src/services/importGuideLogos.ts from src/services/importGuideLogos/*.svg: each mark as a
// data: URI, keyed by the import guide's card id. Run after changing a logo file.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/services/importGuideLogos');
/** Card id → its file. */
export const LOGO_FILES = {
  dbt: 'dbt.svg',
  databricks: 'databricks.svg',
  snowflake: 'snowflake.svg',
  powerBi: 'power-bi.svg',
  fabric: 'fabric.svg',
  sqlServer: 'sql-server.svg',
  postgres: 'postgresql.svg',
  mysql: 'mysql.svg',
};

export function render() {
  const lines = Object.entries(LOGO_FILES).map(([id, file]) =>
    `  ${id}: 'data:image/svg+xml;base64,${readFileSync(join(dir, file)).toString('base64')}',`);
  return [
    '/**',
    ' * GENERATED by scripts/gen-import-guide-logos.mjs from src/services/importGuideLogos/*.svg: do not edit.',
    ' * Each source\'s own mark, unchanged, as a data: image for the import guide (terms: importGuideLogos/LOGOS.md).',
    ' */',
    'export const IMPORT_GUIDE_LOGOS: Readonly<Record<string, string>> = Object.freeze({',
    ...lines,
    '});',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, 'src/services/importGuideLogos.ts'), render());
}
